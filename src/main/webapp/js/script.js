// ============ FEEDBACK FUNCTIONS ============

function openFeedbackModal(recipeId, recipeName) {
    console.log('Opening feedback modal for:', recipeName);
    document.getElementById('feedbackRecipeId').value = recipeId;
    document.getElementById('feedbackRecipeName').value = recipeName;
    document.getElementById('feedbackRating').value = 0;
    document.getElementById('feedbackComment').value = '';
    document.getElementById('feedbackSuggestions').value = '';
    document.getElementById('feedbackCategory').value = '';
    currentRating = 0;
    updateRatingDisplay();
    feedbackModal.style.display = 'block';
}

function closeFeedbackModal() {
    console.log('Closing feedback modal');
    feedbackModal.style.display = 'none';
    currentRating = 0;
}

function setRating(rating) {
    console.log('Rating selected:', rating);
    currentRating = rating;
    document.getElementById('feedbackRating').value = rating;
    
    // Update visual feedback
    const stars = document.querySelectorAll('.star');
    stars.forEach((star, index) => {
        if (index < rating) {
            star.classList.add('active');
        } else {
            star.classList.remove('active');
        }
    });
    
    updateRatingDisplay();
}

function updateRatingDisplay() {
    const ratingDisplay = document.getElementById('ratingDisplay');
    if (currentRating > 0) {
        const labels = ['Poor', 'Fair', 'Good', 'Very Good', 'Excellent'];
        ratingDisplay.textContent = `${currentRating} Star${currentRating > 1 ? 's' : ''} - ${labels[currentRating - 1]}`;
        ratingDisplay.style.color = '#667eea';
    } else {
        ratingDisplay.textContent = 'Please select a rating';
        ratingDisplay.style.color = '#999';
    }
}

function submitFeedback() {
    console.log('Submitting feedback...');
    
    const recipeId = document.getElementById('feedbackRecipeId').value;
    const recipeName = document.getElementById('feedbackRecipeName').value;
    const rating = parseInt(document.getElementById('feedbackRating').value);
    const category = document.getElementById('feedbackCategory').value;
    const comment = document.getElementById('feedbackComment').value;
    const suggestions = document.getElementById('feedbackSuggestions').value;
    
    // Validate
    if (rating === 0) {
        alert('Please select a rating');
        return;
    }
    if (!category) {
        alert('Please select a category');
        return;
    }
    if (!comment.trim()) {
        alert('Please provide a comment');
        return;
    }
    
    const feedback = {
        recipeId: recipeId,
        recipeName: recipeName,
        rating: rating,
        category: category,
        comment: comment.trim(),
        suggestedChanges: suggestions.trim()
    };
    
    console.log('Sending feedback:', feedback);
    
    // Submit to Java API (feedback is on same port 8080 via relative path)
    const feedbackEndpoint = `/api/feedback`;
    
    fetch(feedbackEndpoint, {
        method: 'POST',
        headers: {
            'Content-Type': 'application/json'
        },
        body: JSON.stringify(feedback)
    })
    .then(response => {
        if (!response.ok) {
            throw new Error(`HTTP error! status: ${response.status}`);
        }
        return response.json();
    })
    .then(data => {
        console.log('Feedback submitted successfully:', data);
        alert('✅ Thank you for your feedback! This helps improve future recipes.');
        closeFeedbackModal();
        feedbackForm.reset();
        
        // Show learning insights if available
        fetchLearningInsights();
    })
    .catch(error => {
        console.error('Error submitting feedback:', error);
        alert('❌ Error submitting feedback. Please try again.');
    });
}

function fetchLearningInsights() {
    console.log('Fetching learning insights...');
    
    // Learning insights from Java API (relative path on port 8080)
    const insightsEndpoint = `/api/feedback?action=insights`;
    
    fetch(insightsEndpoint)
        .then(response => response.json())
        .then(data => {
            console.log('Learning Insights:', data);
            if (data.totalFeedback > 5) {
                console.log('🤖 AI Learning Insights:');
                console.log(data.insights);
            }
        })
        .catch(error => console.log('Could not fetch insights:', error));
}

