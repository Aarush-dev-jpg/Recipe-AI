// DOM Elements
const searchInput = document.getElementById('searchInput');
const searchType = document.getElementById('searchType');
const recipeList = document.getElementById('recipeList');
const addRecipeModal = document.getElementById('addRecipeModal');
const addRecipeForm = document.getElementById('addRecipeForm');
const closeModalBtn = document.querySelector('.close');
const feedbackModal = document.getElementById('feedbackModal');
const feedbackForm = document.getElementById('feedbackForm');

// API Configuration
const FLASK_API_BASE = 'http://localhost:5000';
const JAVA_API_BASE = 'http://localhost:8080';
const RELATIVE_API_BASE = '/';

// Configuration for API source (change to 'java' if you want to use Java backend)
const API_SOURCE = 'flask'; // 'flask' or 'java'

// Determine which API base URL to use
const API_BASE = API_SOURCE === 'flask' ? FLASK_API_BASE : RELATIVE_API_BASE;

// Rating state
let currentRating = 0;

console.log(`Using ${API_SOURCE.toUpperCase()} API at ${API_BASE}`);

// Load recipes when page loads
document.addEventListener('DOMContentLoaded', loadAllRecipes);

// Event Listeners
closeModalBtn.onclick = () => addRecipeModal.style.display = 'none';
window.onclick = (event) => {
    if (event.target == addRecipeModal) {
        addRecipeModal.style.display = 'none';
    }
    if (event.target == feedbackModal) {
        closeFeedbackModal();
    }
};

// Add search input event listener for Enter key
searchInput.addEventListener('keypress', function(event) {
    if (event.key === 'Enter') {
        event.preventDefault();
        searchRecipes();
    }
});

addRecipeForm.onsubmit = (e) => {
    e.preventDefault();
    addRecipe();
};

feedbackForm.onsubmit = (e) => {
    e.preventDefault();
    submitFeedback();
};

// Functions
function loadAllRecipes() {
    console.log('Loading all recipes from API');
    const endpoint = `${API_BASE}/api/recipes`;
    
    fetch(endpoint)
        .then(response => {
            if (!response.ok) {
                throw new Error(`HTTP error! status: ${response.status}`);
            }
            return response.json();
        })
        .then(recipes => {
            console.log('Recipes loaded:', recipes);
            displayRecipes(recipes);
        })
        .catch(error => {
            console.error('Error loading recipes:', error);
            recipeList.innerHTML = '<div class="error">Failed to load recipes. Please check that the API is running.</div>';
        });
}

function searchRecipes() {
    const searchValue = searchInput.value.trim();
    if (!searchValue) {
        alert('Please enter a search term');
        return;
    }

    console.log('Searching for:', searchValue);
    const searchTypeValue = searchType.value; // Get the selected search type
    const endpoint = `${API_BASE}/api/search?${searchTypeValue}=${encodeURIComponent(searchValue)}`;
    
    console.log('Request URL:', endpoint);
    
    // Show loading state
    recipeList.innerHTML = '<div class="loading">Searching recipes...</div>';

    fetch(endpoint)
        .then(response => {
            if (!response.ok) {
                throw new Error(`HTTP error! status: ${response.status}`);
            }
            return response.json();
        })
        .then(recipes => {
            console.log('Search results:', recipes);
            displayRecipes(recipes);
        })
        .catch(error => {
            console.error('Error searching recipes:', error);
            recipeList.innerHTML = `<div class="error">Error searching recipes: ${error.message}</div>`;
        });
}

function displayRecipes(recipes) {
    recipeList.innerHTML = '';
    
    if (!recipes || recipes.length === 0) {
        recipeList.innerHTML = '<div class="no-results">😕 No recipes found. Try searching for a different ingredient!</div>';
        return;
    }
    
    recipes.forEach(recipe => {
        const recipeCard = document.createElement('div');
        recipeCard.className = 'recipe-card';
        
        // Check if recipe was generated by Gemini
        const sourceIcon = recipe.source === 'gemini' ? '🤖' : '✅';
        const sourceText = recipe.source === 'gemini' ? 'AI Generated' : 'From Database';
        const source = `<p class="recipe-source">${sourceIcon} ${sourceText}</p>`;
        
        recipeCard.innerHTML = `
            <h3>${recipe.name}</h3>
            ${source}
            <div class="recipe-meta">
                <p><strong>⏱️ Time:</strong> ${recipe.cookingTime || 'N/A'} min</p>
                <p><strong>📊 Level:</strong> ${recipe.difficulty || 'N/A'}</p>
                <p><strong>🏷️ Tags:</strong> ${recipe.categories && recipe.categories.length > 0 ? recipe.categories.join(', ') : 'N/A'}</p>
            </div>
            <div class="recipe-details">
                <h4>📋 Ingredients:</h4>
                <ul>
                    ${recipe.ingredients && recipe.ingredients.length > 0 
                        ? recipe.ingredients.map(ing => `<li>${ing}</li>`).join('')
                        : '<li>No ingredients specified</li>'
                    }
                </ul>
                <h4>👨‍🍳 Instructions:</h4>
                <p>${recipe.instructions || 'No instructions provided'}</p>
            </div>
            <div class="recipe-actions">
                <button onclick="shareRecipe('${recipe.name.replace(/'/g, "\\'")}')">📤 Share Recipe</button>
                <button onclick="openFeedbackModal('${recipe.id || index}', '${recipe.name.replace(/'/g, "\\'")}')">💬 Feedback</button>
            </div>
        `;
        recipeList.appendChild(recipeCard);
    });
}

function showAddRecipeForm() {
    addRecipeModal.style.display = 'block';
}

function addRecipe() {
    const recipe = {
        name: document.getElementById('recipeName').value,
        ingredients: document.getElementById('ingredients').value ? 
            document.getElementById('ingredients').value.split('\n').filter(i => i.trim()) : [],
        instructions: document.getElementById('instructions').value,
        cookingTime: parseInt(document.getElementById('cookingTime').value),
        difficulty: document.getElementById('difficulty').value,
        categories: document.getElementById('categories').value.split('\n').filter(c => c.trim())
    };

    console.log('Adding recipe:', recipe);
    const endpoint = `${API_BASE}/api/recipe/generate`;
    
    // For Flask API, use the generate endpoint
    if (API_SOURCE === 'flask') {
        // Generate recipe with Gemini if using Flask
        fetch(`${API_BASE}/api/recipe/generate`, {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
            },
            body: JSON.stringify({
                ingredient: recipe.name,
                description: `${recipe.name} with ingredients: ${recipe.ingredients.join(', ')}`
            })
        })
        .then(response => response.json())
        .then(generatedRecipe => {
            console.log('Recipe generated:', generatedRecipe);
            addRecipeModal.style.display = 'none';
            addRecipeForm.reset();
            loadAllRecipes();
        })
        .catch(error => {
            console.error('Error adding recipe:', error);
            alert('Error adding recipe: ' + error.message);
        });
    } else {
        // For Java API
        fetch(`${API_BASE}/api/recipes`, {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
            },
            body: JSON.stringify(recipe)
        })
        .then(response => response.json())
        .then(newRecipe => {
            console.log('Recipe added:', newRecipe);
            addRecipeModal.style.display = 'none';
            addRecipeForm.reset();
            loadAllRecipes();
        })
        .catch(error => {
            console.error('Error adding recipe:', error);
            alert('Error adding recipe: ' + error.message);
        });
    }
}

function getRecommendations(recipeName) {
    console.log('Getting recommendations for:', recipeName);
    
    // For Flask API, generate similar recipes using Gemini
    if (API_SOURCE === 'flask') {
        fetch(`${API_BASE}/api/recipe/generate`, {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
            },
            body: JSON.stringify({
                description: `Generate a recipe similar to ${recipeName}`
            })
        })
        .then(response => response.json())
        .then(recipe => {
            console.log('Recommendation generated:', recipe);
            displayRecipes([recipe]);
            window.scrollTo(0, 0);
        })
        .catch(error => console.error('Error getting recommendations:', error));
    } else {
        // For Java API
        fetch(`${API_BASE}/api/recommend?recipe=${encodeURIComponent(recipeName)}`)
            .then(response => {
                if (!response.ok) {
                    throw new Error(`HTTP error! status: ${response.status}`);
                }
                return response.json();
            })
            .then(recipes => {
                console.log('Recommendations:', recipes);
                displayRecipes(recipes);
                window.scrollTo(0, 0);
            })
            .catch(error => console.error('Error getting recommendations:', error));
    }
}

function shareRecipe(recipeName) {
    const text = `Check out this recipe: ${recipeName}\n\nSearch for it on our Recipe Recommender!`;
    
    if (navigator.share) {
        navigator.share({
            title: 'Recipe Recommender',
            text: text,
            url: window.location.href
        }).catch(err => console.log('Error sharing:', err));
    } else {
        // Fallback: Copy to clipboard
        navigator.clipboard.writeText(text).then(() => {
            alert('Recipe link copied to clipboard!');
        }).catch(err => console.error('Failed to copy:', err));
    }
}

